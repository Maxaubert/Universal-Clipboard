//! Pasteboard type names and the rules that look only at the list of types.
//!
//! Looking at the types reads no content. So the backend first sorts a change by its types and
//! reads content only when the clip may be synced. This module has no OS calls and is tested on
//! every OS.

/// Plain text (`NSPasteboardTypeString`).
pub const TEXT: &str = "public.utf8-plain-text";
/// HTML (`NSPasteboardTypeHTML`).
pub const HTML: &str = "public.html";
/// PNG image (`NSPasteboardTypePNG`).
pub const PNG: &str = "public.png";
/// TIFF image (`NSPasteboardTypeTIFF`). Most Mac apps put images on the pasteboard as TIFF.
pub const TIFF: &str = "public.tiff";

/// Our origin marker (echo layer 1, plan 3.8). Written with every clip we put on the pasteboard.
pub const MARKER: &str = "io.github.maxaubert.uclip.origin";

/// Set by Apple's Universal Clipboard when a clip came from another Apple device (plan 3.8,
/// decision 8).
pub const REMOTE_CLIPBOARD: &str = "com.apple.is-remote-clipboard";

/// Private markers from nspasteboard.org (plan 3.10). A clip with any of them is never sent.
pub const PRIVATE: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Types that mean "a file or folder was copied" (plan 3.8). The whole clip is skipped.
pub const FILES: [&str; 3] = [
    "public.file-url",
    // The old name, still set by some apps next to the new one.
    "NSFilenamesPboardType",
    // A file that an app promises to write later (for example a photo dragged from Photos).
    "com.apple.pasteboard.promised-file-url",
];

/// What the list of types says about a clip, before any content is read.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Kinds {
    /// Our origin marker is present.
    pub marker: bool,
    /// A private marker is present.
    pub private: bool,
    /// A file reference is present.
    pub files: bool,
    /// The clip came through Apple's Universal Clipboard.
    pub remote: bool,
}

impl Kinds {
    /// Sort a clip by its types.
    pub fn of<S: AsRef<str>>(types: &[S]) -> Self {
        let has = |name: &str| types.iter().any(|t| t.as_ref() == name);
        Self {
            marker: has(MARKER),
            private: PRIVATE.iter().any(|t| has(t)),
            files: FILES.iter().any(|t| has(t)),
            remote: has(REMOTE_CLIPBOARD),
        }
    }

    /// True if the content must not be read, because the clip is never sent.
    pub fn skip_content(&self) -> bool {
        self.marker || self.private || self.files
    }
}

/// Decode an HTML part to UTF-8.
///
/// Browsers put UTF-8 on the pasteboard, but some older apps write UTF-16 with a byte order
/// mark. Anything else is dropped (the text part is still synced).
pub fn html_to_utf8(bytes: &[u8]) -> Option<Vec<u8>> {
    let utf16 = |be: bool, rest: &[u8]| -> Option<Vec<u8>> {
        let (pairs, tail) = rest.as_chunks::<2>();
        if !tail.is_empty() {
            return None;
        }
        let units = pairs.iter().map(|c| {
            if be {
                u16::from_be_bytes([c[0], c[1]])
            } else {
                u16::from_le_bytes([c[0], c[1]])
            }
        });
        char::decode_utf16(units)
            .collect::<Result<String, _>>()
            .ok()
            .map(String::into_bytes)
    };
    match bytes {
        [0xEF, 0xBB, 0xBF, rest @ ..] => std::str::from_utf8(rest).ok().map(|_| rest.to_vec()),
        [0xFF, 0xFE, rest @ ..] => utf16(false, rest),
        [0xFE, 0xFF, rest @ ..] => utf16(true, rest),
        _ => std::str::from_utf8(bytes).ok().map(|_| bytes.to_vec()),
    }
}

/// What [`with_charset_meta`] puts in front of HTML without a charset.
pub const CHARSET_META: &[u8] = b"<meta charset=\"utf-8\">";

/// UTF-8 HTML for the pasteboard. AppKit (TextEdit, Mail, Notes) reads HTML that names no
/// charset as Latin-1, so "blåbær" would paste as "blÃ¥bÃ¦r". Chromium adds the same tag.
pub fn with_charset_meta(html: &[u8]) -> Vec<u8> {
    let head = &html[..html.len().min(1024)];
    if head
        .to_ascii_lowercase()
        .windows(7)
        .any(|w| w == b"charset")
    {
        return html.to_vec();
    }
    [CHARSET_META, html].concat()
}

/// Remove the tag [`with_charset_meta`] adds, so a clip that went through a Mac is not
/// changed by it.
pub fn strip_charset_meta(html: Vec<u8>) -> Vec<u8> {
    match html.strip_prefix(CHARSET_META) {
        Some(rest) => rest.to_vec(),
        None => html,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn charset_meta_round_trip() {
        let h = "<b>blåbær</b>".as_bytes();
        let w = with_charset_meta(h);
        assert!(w.starts_with(CHARSET_META));
        assert_eq!(strip_charset_meta(w), h);
        // HTML that already names its charset is left alone.
        let named = b"<meta charset=\"iso-8859-1\"><b>x</b>";
        assert_eq!(with_charset_meta(named), named);
        assert_eq!(strip_charset_meta(named.to_vec()), named);
    }

    /// Type lists in the shape real apps write them. They are written from public sources, not
    /// recorded on Max's Mac: tests never read the general pasteboard. The `mac-b` VM can
    /// record real lists later (plan M5 accept).
    #[test]
    fn recorded_type_sets() {
        // TextEdit plain text copy.
        let k = Kinds::of(&["public.utf8-plain-text", "NSStringPboardType"]);
        assert_eq!(k, Kinds::default());

        // A password manager copy.
        let k = Kinds::of(&[
            "public.utf8-plain-text",
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
        ]);
        assert!(k.private && k.skip_content());

        // Finder: one copied file.
        let k = Kinds::of(&[
            "public.file-url",
            "CorePasteboardFlavorType 0x6675726C",
            "dyn.ah62d4rv4gu8y6y4grf0gn5xbrzw1gydcr7u1e3cytf2gn",
            "NSFilenamesPboardType",
            "public.utf8-plain-text",
            "public.utf16-external-plain-text",
            "com.apple.icns",
        ]);
        assert!(k.files && k.skip_content());

        // Our own write.
        let k = Kinds::of(&["public.utf8-plain-text", MARKER]);
        assert!(k.marker && k.skip_content());

        // A clip from an iPhone through Universal Clipboard.
        let k = Kinds::of(&["com.apple.is-remote-clipboard", "public.utf8-plain-text"]);
        assert!(k.remote && !k.skip_content());

        // Screenshot to clipboard (cmd-ctrl-shift-4).
        let k = Kinds::of(&["public.png", "Apple PNG pasteboard type"]);
        assert_eq!(k, Kinds::default());
    }

    #[test]
    fn each_private_marker_alone() {
        for t in PRIVATE {
            assert!(Kinds::of(&[TEXT, t]).private, "{t}");
        }
    }

    #[test]
    fn html_decoding() {
        assert_eq!(html_to_utf8(b"<b>x</b>").unwrap(), b"<b>x</b>");
        assert_eq!(html_to_utf8(b"\xEF\xBB\xBF<i>").unwrap(), b"<i>");
        let le: Vec<u8> = [0xFF, 0xFE]
            .into_iter()
            .chain("<p>\u{e6}</p>".encode_utf16().flat_map(u16::to_le_bytes))
            .collect();
        assert_eq!(html_to_utf8(&le).unwrap(), "<p>\u{e6}</p>".as_bytes());
        let be: Vec<u8> = [0xFE, 0xFF]
            .into_iter()
            .chain("<a>".encode_utf16().flat_map(u16::to_be_bytes))
            .collect();
        assert_eq!(html_to_utf8(&be).unwrap(), b"<a>");
        assert_eq!(html_to_utf8(b"\xFF\xFE\x00"), None);
        assert_eq!(html_to_utf8(b"\xC3\x28"), None);
    }
}
