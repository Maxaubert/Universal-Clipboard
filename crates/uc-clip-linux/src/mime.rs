//! MIME and target rules shared by the X11 and Wayland backends.
//!
//! This module is pure: it decides which offered types to read, how to turn them into a
//! [`Snapshot`], and which types to offer on a write. The backends only move bytes. So the
//! rules are tested on every OS, also on Windows and macOS.

use std::sync::Arc;

use uc_clip::{ClipboardError, Format, RawPart, Snapshot};

/// Our private origin marker (plan 3.8, echo layer 1). A clip that carries it was written by us.
pub const MARKER: &str = "application/x-uclip-origin";

/// The bytes we serve for the marker type. Readers only check that the type is offered.
pub const MARKER_VALUE: &[u8] = b"1";

/// The KDE password manager hint (plan 3.10). KeePassXC and KDE apps set it to `secret`.
pub const KDE_PASSWORD_HINT: &str = "x-kde-passwordManagerHint";

/// Types whose mere presence marks a copy as private. These are the nspasteboard.org names,
/// which some cross-platform apps also offer on Linux.
pub const PRIVATE_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// A list of URIs. It holds a file clip when one line is a `file:` URI (plan 3.8).
pub const URI_LIST: &str = "text/uri-list";

/// GNOME Files (Nautilus) and other GTK file managers offer this type for copied files.
pub const GNOME_COPIED_FILES: &str = "x-special/gnome-copied-files";

/// HTML.
pub const HTML: &str = "text/html";

/// PNG.
pub const PNG: &str = "image/png";

/// UTF-8 text types, in the order we prefer to read them.
pub const UTF8_TEXT: &[&str] = &["text/plain;charset=utf-8", "UTF8_STRING", "text/plain"];

/// Latin-1 text (X11 `STRING`). Read only when no UTF-8 type is offered.
pub const LATIN1_TEXT: &str = "STRING";

/// Text types we offer on a write. All carry the same UTF-8 bytes. (`TEXT` is answered on
/// X11 with type `UTF8_STRING`.)
pub const WRITE_TEXT: &[&str] = &[
    "text/plain;charset=utf-8",
    "UTF8_STRING",
    "text/plain",
    "TEXT",
];

/// The largest part we read, in bytes. It is far above every size cap of the core (image:
/// 25 MiB), so the core still makes the real decision. It only stops a broken source from
/// filling memory.
pub const MAX_READ: usize = 64 * 1024 * 1024;

/// How to turn the bytes of a text type into UTF-8.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TextEncoding {
    /// Already UTF-8.
    Utf8,
    /// ISO 8859-1 (X11 `STRING`).
    Latin1,
}

/// What to read, given the offered types.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ReadPlan {
    /// Our marker is offered.
    pub marker: bool,
    /// A private type is offered (no need to read anything).
    pub private: bool,
    /// The KDE hint is offered; its value decides.
    pub kde_hint: bool,
    /// GNOME copied files is offered.
    pub files: bool,
    /// `text/uri-list` is offered; its content decides.
    pub uri_list: bool,
    /// The text type to read.
    pub text: Option<(String, TextEncoding)>,
    /// `text/html` is offered.
    pub html: bool,
    /// `image/png` is offered.
    pub png: bool,
}

/// Decide what to read from the offered types.
pub fn plan(offered: &[String]) -> ReadPlan {
    let has = |m: &str| offered.iter().any(|o| o == m);
    // The offered name is kept as offered (for example `charset=UTF-8`), because the owner
    // matches it exactly.
    let find_ci = |m: &str| offered.iter().find(|o| o.eq_ignore_ascii_case(m)).cloned();
    let text = UTF8_TEXT
        .iter()
        .find_map(|m| find_ci(m))
        .map(|m| (m, TextEncoding::Utf8))
        .or_else(|| has(LATIN1_TEXT).then(|| (LATIN1_TEXT.to_owned(), TextEncoding::Latin1)));
    ReadPlan {
        marker: has(MARKER),
        private: PRIVATE_TYPES.iter().any(|m| has(m)),
        kde_hint: has(KDE_PASSWORD_HINT),
        files: has(GNOME_COPIED_FILES),
        uri_list: has(URI_LIST),
        text,
        html: has(HTML),
        png: has(PNG),
    }
}

/// The value of the KDE hint means "private". KDE sets `secret`; we ignore case, spaces and
/// a trailing NUL.
pub fn is_secret_hint(value: &[u8]) -> bool {
    let v = String::from_utf8_lossy(value);
    v.trim_matches(|c: char| c.is_whitespace() || c == '\0')
        .eq_ignore_ascii_case("secret")
}

/// A `text/uri-list` holds at least one `file:` URI (RFC 2483: comment lines start with `#`).
pub fn uri_list_has_files(bytes: &[u8]) -> bool {
    String::from_utf8_lossy(bytes).lines().any(|l| {
        let l = l.trim();
        !l.starts_with('#') && l.len() >= 5 && l[..5].eq_ignore_ascii_case("file:")
    })
}

/// Turn text bytes into UTF-8. Invalid UTF-8 is repaired, so the wire never holds it.
pub fn decode_text(bytes: Vec<u8>, enc: TextEncoding) -> Vec<u8> {
    match enc {
        TextEncoding::Utf8 => match String::from_utf8(bytes) {
            Ok(s) => s.into_bytes(),
            Err(e) => String::from_utf8_lossy(e.as_bytes())
                .into_owned()
                .into_bytes(),
        },
        TextEncoding::Latin1 => bytes
            .into_iter()
            .map(char::from)
            .collect::<String>()
            .into_bytes(),
    }
}

/// Build a snapshot from the offered types and a function that reads one type.
///
/// `fetch` returns `Ok(None)` when the owner refused or the type went away. Rules:
/// - marker: nothing else is read (echo layer 1);
/// - private hint: nothing else is read; a hint that cannot be read counts as private;
/// - file clip: nothing else is read; a `text/uri-list` that cannot be read counts as files;
/// - else text, HTML and PNG are read. A part that fails to read is left out.
pub fn build_snapshot<F>(seq: u64, offered: &[String], mut fetch: F) -> Snapshot
where
    F: FnMut(&str) -> Result<Option<Vec<u8>>, ClipboardError>,
{
    let p = plan(offered);
    let mut snap = Snapshot {
        seq,
        ..Snapshot::default()
    };
    if p.marker {
        snap.has_marker = true;
        return snap;
    }
    if p.private
        || (p.kde_hint
            && match fetch(KDE_PASSWORD_HINT) {
                Ok(Some(v)) => is_secret_hint(&v),
                Ok(None) | Err(_) => true,
            })
    {
        snap.private = true;
        return snap;
    }
    if p.files
        || (p.uri_list
            && match fetch(URI_LIST) {
                Ok(Some(v)) => uri_list_has_files(&v),
                Ok(None) => false,
                Err(_) => true,
            })
    {
        snap.has_files = true;
        return snap;
    }
    if let Some((mime, enc)) = p.text
        && let Ok(Some(b)) = fetch(&mime)
    {
        snap.parts.push((Format::TextPlain, decode_text(b, enc)));
    }
    if p.html
        && let Ok(Some(b)) = fetch(HTML)
    {
        snap.parts.push((Format::TextHtml, b));
    }
    if p.png
        && let Ok(Some(b)) = fetch(PNG)
    {
        snap.parts.push((Format::ImagePng, b));
    }
    snap
}

/// One served type and its bytes.
pub type Item = (String, Arc<Vec<u8>>);

/// The types to offer for a write of `parts`, plus our marker. Bytes are shared, not copied.
pub fn write_items(parts: &[RawPart]) -> Vec<Item> {
    let mut items = Vec::new();
    for (format, bytes) in parts {
        let bytes = Arc::new(bytes.clone());
        match format {
            Format::TextPlain => {
                for m in WRITE_TEXT {
                    items.push(((*m).to_owned(), bytes.clone()));
                }
            }
            Format::TextHtml => items.push((HTML.to_owned(), bytes)),
            Format::ImagePng => items.push((PNG.to_owned(), bytes)),
        }
    }
    items.push((MARKER.to_owned(), Arc::new(MARKER_VALUE.to_vec())));
    items
}

/// Turn raw `(type, bytes)` pairs into served items, with no marker. For tests and tools that
/// must look like another app.
pub fn raw_items(items: &[(&str, &[u8])]) -> Vec<Item> {
    items
        .iter()
        .map(|(m, b)| ((*m).to_owned(), Arc::new(b.to_vec())))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    fn offered(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| (*s).to_owned()).collect()
    }

    fn snap(list: &[(&str, &[u8])]) -> (Snapshot, Vec<String>) {
        let map: HashMap<String, Vec<u8>> = list
            .iter()
            .map(|(m, b)| ((*m).to_owned(), b.to_vec()))
            .collect();
        let types: Vec<String> = list.iter().map(|(m, _)| (*m).to_owned()).collect();
        let mut asked = Vec::new();
        let s = build_snapshot(7, &types, |m| {
            asked.push(m.to_owned());
            Ok(map.get(m).cloned())
        });
        (s, asked)
    }

    #[test]
    fn text_preference_order() {
        let p = plan(&offered(&["text/plain", "UTF8_STRING", "STRING"]));
        assert_eq!(p.text, Some(("UTF8_STRING".into(), TextEncoding::Utf8)));
        let p = plan(&offered(&["STRING", "TEXT"]));
        assert_eq!(p.text, Some(("STRING".into(), TextEncoding::Latin1)));
        let p = plan(&offered(&["text/plain;charset=UTF-8"]));
        assert_eq!(
            p.text,
            Some(("text/plain;charset=UTF-8".into(), TextEncoding::Utf8))
        );
        assert_eq!(plan(&offered(&["TARGETS", "image/jpeg"])).text, None);
    }

    #[test]
    fn text_html_png_are_read() {
        let (s, _) = snap(&[
            ("UTF8_STRING", b"hi"),
            ("text/html", b"<b>hi</b>"),
            ("image/png", b"\x89PNG"),
            ("image/jpeg", b"x"),
        ]);
        assert_eq!(s.seq, 7);
        assert!(!s.has_marker && !s.private && !s.has_files);
        assert_eq!(
            s.parts,
            vec![
                (Format::TextPlain, b"hi".to_vec()),
                (Format::TextHtml, b"<b>hi</b>".to_vec()),
                (Format::ImagePng, b"\x89PNG".to_vec()),
            ]
        );
    }

    #[test]
    fn marker_stops_all_reads() {
        let (s, asked) = snap(&[("UTF8_STRING", b"hi"), (MARKER, b"1")]);
        assert!(s.has_marker);
        assert!(s.parts.is_empty());
        assert!(asked.is_empty());
    }

    #[test]
    fn kde_secret_hint_is_private_and_content_is_not_read() {
        let (s, asked) = snap(&[("UTF8_STRING", b"pw"), (KDE_PASSWORD_HINT, b"secret")]);
        assert!(s.private);
        assert!(s.parts.is_empty());
        assert_eq!(asked, vec![KDE_PASSWORD_HINT.to_owned()]);
        let (s, _) = snap(&[("UTF8_STRING", b"pw"), (KDE_PASSWORD_HINT, b"accept")]);
        assert!(!s.private);
        assert_eq!(s.parts.len(), 1);
    }

    #[test]
    fn unreadable_hint_counts_as_private() {
        let types = offered(&["UTF8_STRING", KDE_PASSWORD_HINT]);
        let s = build_snapshot(1, &types, |m| {
            if m == KDE_PASSWORD_HINT {
                Err(ClipboardError::Other("x".into()))
            } else {
                Ok(Some(b"pw".to_vec()))
            }
        });
        assert!(s.private);
        let s = build_snapshot(1, &types, |_| Ok(None));
        assert!(s.private);
    }

    #[test]
    fn nspasteboard_types_are_private() {
        let (s, asked) = snap(&[
            ("UTF8_STRING", b"pw"),
            ("org.nspasteboard.ConcealedType", b""),
        ]);
        assert!(s.private);
        assert!(asked.is_empty());
    }

    #[test]
    fn secret_hint_value_rules() {
        assert!(is_secret_hint(b"secret"));
        assert!(is_secret_hint(b"Secret\n"));
        assert!(is_secret_hint(b"secret\0"));
        assert!(!is_secret_hint(b""));
        assert!(!is_secret_hint(b"accept"));
    }

    #[test]
    fn file_clips_are_skipped() {
        let (s, _) = snap(&[
            (
                "text/uri-list",
                b"# comment\r\nfile:///home/u/report.pdf\r\n",
            ),
            ("UTF8_STRING", b"report.pdf"),
        ]);
        assert!(s.has_files);
        assert!(s.parts.is_empty());
        let (s, asked) = snap(&[
            (GNOME_COPIED_FILES, b"copy\nfile:///a"),
            ("UTF8_STRING", b"a"),
        ]);
        assert!(s.has_files);
        assert!(asked.is_empty());
    }

    #[test]
    fn web_links_are_not_files() {
        let (s, _) = snap(&[
            ("text/uri-list", b"https://example.org/\r\n"),
            ("UTF8_STRING", b"https://example.org/"),
        ]);
        assert!(!s.has_files);
        assert_eq!(s.parts.len(), 1);
    }

    #[test]
    fn unreadable_uri_list_counts_as_files() {
        let types = offered(&["UTF8_STRING", URI_LIST]);
        let s = build_snapshot(1, &types, |m| {
            if m == URI_LIST {
                Err(ClipboardError::Busy)
            } else {
                Ok(Some(b"x".to_vec()))
            }
        });
        assert!(s.has_files);
    }

    #[test]
    fn failed_part_is_left_out() {
        let types = offered(&["UTF8_STRING", "image/png"]);
        let s = build_snapshot(1, &types, |m| {
            if m == PNG {
                Err(ClipboardError::Busy)
            } else {
                Ok(Some(b"t".to_vec()))
            }
        });
        assert_eq!(s.parts, vec![(Format::TextPlain, b"t".to_vec())]);
    }

    #[test]
    fn text_decoding() {
        assert_eq!(
            decode_text(vec![0x63, 0x61, 0x66, 0xE9], TextEncoding::Latin1),
            "café".as_bytes()
        );
        assert_eq!(decode_text(b"ok".to_vec(), TextEncoding::Utf8), b"ok");
        assert_eq!(
            decode_text(vec![b'a', 0xFF], TextEncoding::Utf8),
            "a\u{FFFD}".as_bytes()
        );
    }

    #[test]
    fn write_items_offer_all_text_types_and_marker() {
        let items = write_items(&[
            (Format::TextPlain, b"t".to_vec()),
            (Format::TextHtml, b"<i>t</i>".to_vec()),
            (Format::ImagePng, b"png".to_vec()),
        ]);
        let names: Vec<&str> = items.iter().map(|(m, _)| m.as_str()).collect();
        for m in WRITE_TEXT {
            assert!(names.contains(m));
        }
        assert!(names.contains(&HTML) && names.contains(&PNG));
        assert_eq!(names.last(), Some(&MARKER));
        // What we write must read back as our own clip.
        let offered: Vec<String> = names.iter().map(|s| (*s).to_owned()).collect();
        assert!(plan(&offered).marker);
        // And the same text without the marker reads back as text.
        let raw = raw_items(&[("UTF8_STRING", b"t")]);
        assert_eq!(raw.len(), 1);
    }
}
